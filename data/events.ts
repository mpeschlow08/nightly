export function getEventBySlug(slug: string) {
  return nightlyEvents.find((event) => event.slug === slug);
}

export function getEventSlugs() {
  return nightlyEvents.map((event) => ({ slug: event.slug }));
}

export function getRelatedEvents(event: NightlyEvent) {
  return nightlyEvents
    .filter((item) => item.id !== event.id && (item.venueSlug === event.venueSlug || item.genres.some((genre) => event.genres.includes(genre))))
    .slice(0, 4);
}
